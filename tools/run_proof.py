"""Regenerate headless proof for a phase. Usage: python tools/run_proof.py [phase1]

For every tests/scenarios/<name>.json (optionally <name>.inputs.json):
  - runs the real CLI (python -m game.headless) twice, checks byte-identical output (determinism)
  - saves docs/proof/<phase>/<name>.jsonl and a summary.md (events + end line)
Also saves pytest output to docs/proof/<phase>/pytest.txt. Exit 1 if anything fails.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCN = ROOT / "tests" / "scenarios"
SEED, TICKS = 42, 3600


def headless(scn: Path, out: Path):
    night = json.loads(scn.read_text(encoding="utf-8")).get("_night", 1)
    cmd = [sys.executable, "-m", "game.headless", "--seed", str(SEED), "--night", str(night),
           "--ticks", str(TICKS), "--out", str(out), "--scenario", str(scn)]
    inp = scn.with_name(scn.stem + ".inputs.json")
    if inp.exists():
        cmd += ["--inputs", str(inp)]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    return r.returncode, r.stderr, " ".join(Path(c).name if "/" in c or "\\" in c else c for c in cmd[1:])


def main():
    phase = sys.argv[1] if len(sys.argv) > 1 else "phase1"
    dest = ROOT / "docs" / "proof" / phase
    dest.mkdir(parents=True, exist_ok=True)
    ok = True
    md = [f"# Headless proof ({phase})", "", f"seed={SEED}, ticks={TICKS}. Generated by `python tools/run_proof.py {phase}`.", ""]
    for scn in sorted(SCN.glob("*.json")):
        if scn.name.endswith(".inputs.json") or scn.name.startswith("visual_"):
            continue
        a, b = dest / f"{scn.stem}.jsonl", dest / f"{scn.stem}.rerun.jsonl"
        rc1, err1, cmd = headless(scn, a)
        rc2, _, _ = headless(scn, b)
        same = a.read_bytes() == b.read_bytes() if rc1 == 0 and rc2 == 0 else False
        b.unlink(missing_ok=True)
        ok &= rc1 == 0 and same
        lines = [json.loads(l) for l in a.read_text(encoding="utf-8").splitlines()] if rc1 == 0 else []
        md += [f"## {scn.stem}", f"`{cmd}`", "",
               f"- exit code: {rc1}  - deterministic (2 runs identical): {'YES' if same else 'NO'}" + (f"  - stderr: {err1}" if err1 else ""),
               "", "```"]
        md += [json.dumps(l, ensure_ascii=False) for l in lines if l["type"] != "snapshot"]
        md += ["```", ""]
    r = subprocess.run([sys.executable, "-m", "pytest", "-q"], cwd=ROOT, capture_output=True, text=True)
    (dest / "pytest.txt").write_text(r.stdout + r.stderr, encoding="utf-8")
    ok &= r.returncode == 0
    md += ["## pytest", "```", r.stdout.strip().splitlines()[-1] if r.stdout.strip() else r.stderr, "```"]
    (dest / "summary.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"proof written to {dest} -> {'OK' if ok else 'FAILED'}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
